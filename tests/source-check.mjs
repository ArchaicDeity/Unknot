import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { webcrypto } from 'node:crypto';

const source = await readFile(new URL('../public/assets/source-check.js', import.meta.url));
const { compareSelectedFile, createSourceCheckController } = await import('data:text/javascript;base64,' + source.toString('base64'));
const bytes = new TextEncoder().encode('<?php class Example {}\n');
const digest = Array.from(new Uint8Array(await webcrypto.subtle.digest('SHA-256', bytes)), b => b.toString(16).padStart(2, '0')).join('');
const file = { size: bytes.length, slice: (start, end) => ({ arrayBuffer: async () => bytes.slice(start, end).buffer }) };
assert.equal(await compareSelectedFile(file, digest, webcrypto), 'match');
assert.equal(await compareSelectedFile(file, '0'.repeat(64), webcrypto), 'mismatch');
assert.equal(await compareSelectedFile(file, digest, {}), 'unavailable');
let read = false;
assert.equal(await compareSelectedFile({ size: 2 * 1024 * 1024 + 1, slice: () => { read = true; } }, digest, webcrypto), 'too-large');
assert.equal(read, false, 'Oversized files are rejected before reading.');
assert.equal(await compareSelectedFile({ size: 1, slice: () => ({ arrayBuffer: async () => bytes.buffer }) }, digest, webcrypto), 'changed');
assert.equal(await compareSelectedFile({ size: 1, slice: () => ({ arrayBuffer: async () => { throw new Error('denied'); } }) }, digest, webcrypto), 'unreadable');

const elements = { input: { value: '', files: [], addEventListener(name, callback) { this.callback = callback; } }, choose: {}, status: {} };
let finish;
const controller = createSourceCheckController(elements, () => new Promise(resolve => { finish = resolve; }));
const node = { id: 'file:A.php', sourceSha256: digest };
const report = { schemaVersion: 2 };
controller.update(report, node);
assert.equal(elements.choose.hidden, false);
elements.input.files = [file];
const pending = elements.input.callback();
assert.match(elements.status.textContent, /Comparing/);
controller.update(report, { id: 'file:B.php', sourceSha256: digest });
finish('match');
await pending;
assert.doesNotMatch(elements.status.textContent, /bytes match/, 'An old result cannot appear under a different selected file.');
controller.update(report, node);
elements.input.files = [file];
const reportPending = elements.input.callback();
controller.update({ schemaVersion: 2 }, node);
finish('mismatch');
await reportPending;
assert.doesNotMatch(elements.status.textContent, /do not match/, 'An old result cannot appear under a different report.');
controller.update({ schemaVersion: 1 }, node);
assert.equal(elements.choose.hidden, true);
assert.match(elements.status.textContent, /no source fingerprints/i);
controller.update({ schemaVersion: 2 }, { id: 'file:failed', sourceSha256: null });
assert.equal(elements.choose.hidden, true);
assert.match(elements.status.textContent, /not parsed cleanly/);
controller.update(null, null);
assert.equal(elements.choose.hidden, true);
console.log('Local source comparison checks passed.');
